"""
Extracts the rows the executive-overview dashboard (dashboard.html) needs from the real
Tableau-style Superstore sample (sample_-_superstore.xls), and writes them out as a
compact JS array literal (dashboard_data.js) for client-side aggregation.

Scope: United States only (the dashboard's map is US-only). No year split any more —
the dashboard filters by an arbitrary date range (its own date picker) instead of a
fixed current-year-vs-prior-year comparison, so every US row across every year in the
file is included.

Real columns used directly: Order Date, Segment, Region, State/Province, Category,
Sub-Category, Customer Name, Sales, Profit, Order ID.
Not a real column — approximated: "Manufacturer" (first word of Product Name), the
same heuristic the public Tableau Superstore tutorials use, since this dataset has no
manufacturer field of its own.

Output: dashboard_data.js — `const DASH_ROWS = [...]`. dashboard.html loads this file
directly (regenerate this script if the source .xls changes; don't hand-edit the .js).
"""
import json

import pandas as pd

SRC = r"C:\Users\Haim\OneDrive - Shmulik Yoffe\Desktop\Roster\1_O-output\projects\speaker-development\hayadata-2026-talk\demo\sample_-_superstore.xls"
OUT = r"C:\Users\Haim\OneDrive - Shmulik Yoffe\Desktop\Roster\1_O-output\projects\speaker-development\hayadata-2026-talk\demo\dashboard_data.js"

STATE_ABBR = {
    'Alabama': 'AL', 'Alaska': 'AK', 'Arizona': 'AZ', 'Arkansas': 'AR', 'California': 'CA',
    'Colorado': 'CO', 'Connecticut': 'CT', 'Delaware': 'DE', 'District of Columbia': 'DC',
    'Florida': 'FL', 'Georgia': 'GA', 'Hawaii': 'HI', 'Idaho': 'ID', 'Illinois': 'IL',
    'Indiana': 'IN', 'Iowa': 'IA', 'Kansas': 'KS', 'Kentucky': 'KY', 'Louisiana': 'LA',
    'Maine': 'ME', 'Maryland': 'MD', 'Massachusetts': 'MA', 'Michigan': 'MI', 'Minnesota': 'MN',
    'Mississippi': 'MS', 'Missouri': 'MO', 'Montana': 'MT', 'Nebraska': 'NE', 'Nevada': 'NV',
    'New Hampshire': 'NH', 'New Jersey': 'NJ', 'New Mexico': 'NM', 'New York': 'NY',
    'North Carolina': 'NC', 'North Dakota': 'ND', 'Ohio': 'OH', 'Oklahoma': 'OK', 'Oregon': 'OR',
    'Pennsylvania': 'PA', 'Rhode Island': 'RI', 'South Carolina': 'SC', 'South Dakota': 'SD',
    'Tennessee': 'TN', 'Texas': 'TX', 'Utah': 'UT', 'Vermont': 'VT', 'Virginia': 'VA',
    'Washington': 'WA', 'West Virginia': 'WV', 'Wisconsin': 'WI', 'Wyoming': 'WY',
}

df = pd.read_excel(SRC, sheet_name='Orders')
df = df[df['Country/Region'] == 'United States'].copy()
df['Order Date'] = pd.to_datetime(df['Order Date'])
df['Manufacturer'] = df['Product Name'].str.split().str[0]
df['StAbbr'] = df['State/Province'].map(STATE_ABBR)

rows = []
for _, r in df.iterrows():
    rows.append({
        'd':   r['Order Date'].strftime('%Y-%m-%d'),
        'rg':  r['Region'],
        'st':  r['StAbbr'] if pd.notna(r['StAbbr']) else None,
        'sg':  r['Segment'],
        'mf':  r['Manufacturer'],
        'ct':  r['Category'],
        'sc':  r['Sub-Category'],
        'cu':  r['Customer Name'],
        's':   round(float(r['Sales']), 2),
        'p':   round(float(r['Profit']), 2),
        'oid': r['Order ID'],
    })

min_date = df['Order Date'].min().strftime('%Y-%m-%d')
max_date = df['Order Date'].max().strftime('%Y-%m-%d')

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by generate_dashboard_data.py from sample_-_superstore.xls — do not hand-edit.\n')
    f.write(f"const DATA_MIN_DATE = '{min_date}';\n")
    f.write(f"const DATA_MAX_DATE = '{max_date}';\n")
    f.write('const DASH_ROWS = ')
    f.write(json.dumps(rows, separators=(',', ':')))
    f.write(';\n')

print(f"Wrote {len(rows)} rows ({min_date} -> {max_date}) to:\n  {OUT}")
